"""Builds reports/03_strategy_research_matrix.md from reports/tables/p3_experiment_log.csv and trade files."""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from audit import md_table
from load import ROOT

TAB = ROOT / "reports" / "tables"
TR = ROOT / "reports" / "trades"

LOGIC = {
    "H00_random_baseline": ("Benchmark", "Random side, random minute 15:00–19:00 server, SL 1×ATR15, TP 1.5R. Measures pure cost drag."),
    "H01_asia_range_breakout": ("Breakout / Model D", "OCO stop orders beyond the Asian range (02:00–09:00 server), active 10:00–17:00; SL opposite side or mid; exit 19:00."),
    "H02_asia_sweep_reverse": ("ICT liquidity sweep", "Price takes the Asian high/low, then an M5/M15 bar closes back inside → fade at market; SL beyond the sweep extreme."),
    "H03_pdhl_sweep_reverse": ("ICT / failed breakout (Model E)", "Same as H02 with previous-day high/low."),
    "H04_ny_opening_range_breakout": ("Breakout / Model F", "OCO stops at the 15/30-min opening range after 16:30 server (09:30 NY); SL other side; entries until 19:00, exit 21:00."),
    "H05_trend_pullback": ("Trend following / Model B", "H1 (±H4) EMA50 trend; M5 pullback to EMA20 then close beyond prior bar → market; 15:00–19:00 server."),
    "H06_bollinger_revert_asia": ("Mean reversion / Model C", "M15 close outside Bollinger(20,k) in Asia → fade to the middle band; SL k×ATR15; 60-min time stop."),
    "H07_last_hour_fade": ("Time-of-day (atlas A5)", "At 23:00 server fade the 22:00–23:00 move; SL ×ATR15; flat at 23:50."),
    "H08_ict_sweep_fvg_limit": ("ICT Model A", "Sweep of Asia or PDH/PDL → displacement M5 FVG within 30 min → limit at the FVG edge; SL beyond sweep; TP 1.5–3R."),
}


def main():
    L = pd.read_csv(TAB / "p3_experiment_log.csv")
    meta = json.load(open(ROOT / "reports" / "p3_meta.json"))
    piv = lambda cost, col: L[L.cost == cost].pivot_table(index="config", columns="split", values=col)
    M = pd.DataFrame({"hypothesis": L.drop_duplicates("config").set_index("config").hypothesis})
    for col in ["n", "win_rate", "avg_R", "t_stat", "PF", "maxDD_R", "trades_per_day"]:
        p = piv("C1", col)
        M[f"{col}_dev"], M[f"{col}_val"] = p["dev"], p["val"]
    for cost in ["C0", "C2"]:
        p = piv(cost, "avg_R")
        M[f"avgR_{cost}_dev"], M[f"avgR_{cost}_val"] = p["dev"], p["val"]
    M["DEV_screen"] = (M.n_dev >= 100) & (M.avg_R_dev > 0) & (M.t_stat_dev >= 2) & (M.PF_dev >= 1.10)
    M["VAL_confirm"] = M.DEV_screen & (M.avg_R_val > 0)
    M = M.reset_index()
    tested = M[M.hypothesis != "H00_random_baseline"]
    n_pass = int(tested.DEV_screen.sum())
    n_conf = int(tested.VAL_confirm.sum())

    # family summary
    fam = []
    for h, g in M.groupby("hypothesis"):
        best = g.sort_values("t_stat_dev", ascending=False).iloc[0]
        fam.append({"hypothesis": h, "school": LOGIC[h][0], "configs": len(g), "median_avgR_dev(C1)": g.avg_R_dev.median(),
                    "share_configs_avgR_dev>0": (g.avg_R_dev > 0).mean(), "best_dev_config": best.config.split("|")[1],
                    "best_n_dev": int(best.n_dev), "best_avgR_dev": best.avg_R_dev, "best_t_dev": best.t_stat_dev,
                    "same_config_avgR_val": best.avg_R_val, "same_config_t_val": best.t_stat_val,
                    "verdict": "PASS" if best.VAL_confirm else ("baseline" if h.startswith("H00") else "REJECT")})
    fam = pd.DataFrame(fam)
    base = M[M.hypothesis == "H00_random_baseline"]

    # per-year for the top-4 DEV configs (by t) among tested
    top = tested.sort_values("t_stat_dev", ascending=False).head(4)
    yr_rows = []
    for cid in top.config:
        f = TR / f"{cid.replace('|', '__').replace(',', '_').replace('=', '-')}.csv"
        t = pd.read_csv(f, parse_dates=["t_entry"])
        for y, g in t.groupby(t.t_entry.dt.year):
            yr_rows.append({"config": cid, "year": str(y), "n": len(g), "win_rate": (g.R > 0).mean(), "avg_R": g.R.mean(), "total_R": g.R.sum()})
    yr = pd.DataFrame(yr_rows)

    # null benchmark for the max t across ~56 roughly-correlated configs
    rng = np.random.default_rng(7)
    null_max = np.quantile(np.max(rng.standard_normal((20000, len(tested))), axis=1), [0.5, 0.95])

    cols = ["config", "n_dev", "win_rate_dev", "avg_R_dev", "t_stat_dev", "PF_dev", "maxDD_R_dev", "n_val", "win_rate_val", "avg_R_val", "t_stat_val",
            "avgR_C0_dev", "avgR_C2_dev", "avgR_C0_val", "avgR_C2_val", "DEV_screen", "VAL_confirm"]
    full = M.sort_values(["hypothesis", "config"])[cols].copy()
    full["config"] = full.config.str.replace("_", " ", regex=False)
    logic_md = md_table(pd.DataFrame([{"ID": k, "school": v[0], "exact rule": v[1]} for k, v in LOGIC.items()]))

    report = f"""# Phase 3 — Strategy Research Matrix (first round)

_Generated by `src/run_phase3.py` (engine `src/engine.py`, hypotheses `src/hypotheses.py`) and `src/p3_report.py`. Full log: `reports/tables/p3_experiment_log.csv`; every C1 trade: `reports/trades/`._

## 0. Plain-language summary

* We turned 8 trading ideas from Price Action, ICT/SMC, breakout, trend-following and mean-reversion into exact, programmable rules, and tested **{len(tested)} variants** (+ {len(base)} random benchmarks) on 2022-03 → 2024-06, with real costs.
* **Result: {n_pass} of {len(tested)} variants passed the development screen; {n_conf} confirmed on 2024-07 → 2025-06.** None of these classic ideas, as defined, has a proven edge after costs.
* This is a normal and useful outcome: it tells us which ideas to drop, and the losers point to where an edge might be (§5).

## 1. Protocol (fixed before running)

* Data: M1 Bid + modelled Ask (file minimum spread + measured hourly markup). DEV = 2022-03-16 → 2024-06-30; VAL = 2024-07-02 → 2025-06-30. Holdout untouched.
* Execution: market orders at next-bar open; stop orders fill at the worse of price/open; limits need a 1-point trade-through; **SL wins if SL and TP are in the same minute**; gaps fill at the open; no position crosses the daily halt; one position at a time per hypothesis. Engine unit tests: `tests/test_engine.py`.
* Costs: **C0** spread only · **C1** spread + $0.10 slippage on market/stop orders (base case) · **C2** 2× spread + $0.30 slippage.
* Result unit: **R** = profit ÷ initial risk (entry→SL), after costs.
* **Selection rule:** DEV: n ≥ 100, avg R (C1) > 0, t ≥ 2.0, PF ≥ 1.10 → then the *same* configuration must have avg R (C1) > 0 on VAL. No parameter is re-tuned on VAL.
* Configurations run: {meta['n_configs']} (incl. benchmarks). Under pure chance, the best of {len(tested)} independent tests would show t ≈ {null_max[0]:.1f} (median) and up to ≈ {null_max[1]:.1f} (95th pct.) — so a DEV t of 2 is a weak bar, which is why VAL confirmation is required.

## 2. Hypotheses tested

{logic_md}

## 3. Results by hypothesis family (C1, base costs)

{md_table(fam.round(3), "{:.3f}")}

**Benchmark (random entries, same exits):** avg R at C1 = {base.avg_R_dev.mean():+.3f} (DEV), {base.avg_R_val.mean():+.3f} (VAL); at C0 = {base.avgR_C0_dev.mean():+.3f} / {base.avgR_C0_val.mean():+.3f}. A random trade with a 1×ATR15 stop loses ≈ {abs(base.avg_R_dev.mean()):.2f} R per trade at C1 (spread ≈ {abs(base.avgR_C0_dev.mean()):.2f} R, slippage ≈ {abs(base.avg_R_dev.mean() - base.avgR_C0_dev.mean()):.2f} R) — any real edge must first overcome that.

## 4. Year-by-year for the four best DEV variants (C1)

{md_table(yr.round(3), "{:.3f}")}

## 5. What we learned

1. **Fading liquidity sweeps of the Asian range is clearly wrong** (H02: all 6 variants negative, t ≈ −3.4 to −4.6 in DEV, negative again in VAL). When London/NY take the Asian high or low and briefly close back inside, price usually **continues** in the sweep direction — consistent with the atlas (one-sided Asian breaks hold to the close ≈ 75%).
2. **Bollinger mean reversion in the Asian session loses steadily** (H06: t ≈ −2.4 to −4.6, both sets, even before slippage). Moves that stretch outside the bands in Asia tend to keep going.
3. **Asian-range breakout (H01) and NY opening-range breakout (H04) are ≈ break-even**: positive before costs in places (avg R at C0 up to +0.09), but costs remove it. The best (H04, 30-min OR, 1R) made {M.loc[M.config.str.contains('or_len=30,tp_R=1.0,width_filter=all'), 'avg_R_dev'].iloc[0]:+.3f} R (t={M.loc[M.config.str.contains('or_len=30,tp_R=1.0,width_filter=all'), 't_stat_dev'].iloc[0]:.2f}) in DEV and {M.loc[M.config.str.contains('or_len=30,tp_R=1.0,width_filter=all'), 'avg_R_val'].iloc[0]:+.3f} R in VAL — consistent sign, but too weak to pass.
4. **Trend pullback (H05) and PDH/PDL sweep-reversal (H03) lost in 2022–24 and won in 2024–25.** That is a regime effect (strong uptrend in VAL), not a stable edge.
5. **ICT sweep → FVG → limit entry (H08)** fires rarely (≈ 0.1 per day) and shows no edge; samples are too small to be conclusive either way.
6. **Costs matter enormously at this scale:** moving from C0 to C1 subtracts ≈ 0.05–0.10 R per trade; C2 makes every variant negative. Stops of ≈ 1×ATR15 (~$2 in 2022–24) are too small for market-order strategies.

## 6. Next step (Phase 3b) — registered now, before testing

Because the losing ideas lost *consistently*, their logic inverted is a legitimate new hypothesis — but it was suggested by data we have already seen (DEV **and** VAL), so it **cannot** be confirmed on VAL; it must pass **walk-forward validation and, finally, the untouched holdout**. Pre-registered for Phase 3b:

* **H09 Asian-sweep continuation:** after London/NY takes the Asian high (low) and the retest holds, trade *in the sweep direction*.
* **H10 Asian volatility-break momentum:** M15 close outside Bollinger in Asia → trade *with* the move.
* **H11 Wider intraday exits:** apply H01/H04/H09 with session-end exits and ATR-H1-sized stops (lower cost share).
* **H12 Regime filter:** test whether a pre-defined trend/volatility regime (completed D1/H4 data only) switches H05/H03 on and off — judged by walk-forward, not by the VAL result above.

## 7. Full matrix (C1 unless noted)

{md_table(full.round(3), "{:.3f}")}
"""
    (ROOT / "reports" / "03_strategy_research_matrix.md").write_text(report, encoding="utf-8")
    fam.to_csv(TAB / "p3_family_summary.csv", index=False)
    yr.to_csv(TAB / "p3_top_by_year.csv", index=False)
    print(fam.round(3).to_string())
    print(yr.round(3).to_string())


if __name__ == "__main__":
    main()
