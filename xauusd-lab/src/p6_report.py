"""Builds reports/06_robustness.md."""
import json
import pandas as pd
from audit import md_table
from load import ROOT
TAB = ROOT / "reports" / "tables"

def main():
    G = pd.read_csv(TAB / "p6_swing_grid.csv"); St = pd.read_csv(TAB / "p6_swing_stress.csv")
    I = pd.read_csv(TAB / "p6_intraday_grid.csv"); mc = json.load(open(ROOT / "reports" / "p6_mc.json"))
    S = pd.read_csv(TAB / "p4_swing_summary.csv")
    cfi = S[S.swap == "W_CFI"][["system", "annual_return_%", "sharpe", "maxDD_%", "trades", "years_negative"]]
    sh = G[G.stop_ATR == 2.0].pivot_table(index="N", columns="exit_n", values="sharpe").round(2)
    sh.columns = [f"exit {c}" for c in sh.columns]
    stopmed = G.groupby(G.stop_ATR.fillna(0)).sharpe.median().round(2).rename(index={0: "no stop"}).reset_index()
    ic = I[I.cost == "C1_CFI"].pivot_table(index=["or_len", "vol_quantile"], columns="tp_R", values="avg_R").round(3)
    ic.columns = [f"TP {c}R" for c in ic.columns]
    share = pd.DataFrame([{"cost": c, "variants": int((I.cost == c).sum()), "share avg R > 0": (I[I.cost == c].avg_R > 0).mean(),
                           "share VAL > 0": (I[I.cost == c].avg_R_val > 0).mean(), "share 2025 > 0": (I[I.cost == c].avgR_2025 > 0).mean(),
                           "median avg R": I[I.cost == c].avg_R.median()} for c in ["C1", "C1_CFI", "C2"]])
    sm, im = mc["swing_mc"], mc["intraday_mc"]
    dc = cfi[cfi.system == "S1_donchian20_LO"].iloc[0]
    rep = f"""# Phase 6 — Robustness of the two candidates (DEV + VAL only; holdout still untouched)

_Generated by `src/robust.py`, `src/swing.py`, `src/p6_report.py`. Frozen rules: `rules/xae_swing_v1.json`._

## 0. Plain-language summary

* **Swing candidate (Donchian-20, long only) is robust within the tested sample.** {(G.sharpe > 0).mean() * 100:.0f}% of {len(G)} neighbouring settings (entry 10–55 days, exit 3–55 days, 4 stop types) are profitable; it barely changes with doubled costs, a one-day delay or higher swap; with the **real CFI swap** it makes {dc['annual_return_%']:.1f}%/yr, max drawdown {dc['maxDD_%']:.1f}%, Sharpe {dc.sharpe:.2f}. Monte Carlo: 5th–95th percentile annual return {sm['ann_ret_p5']:.1f}% → {sm['ann_ret_p95']:.1f}%, 95th-percentile drawdown {sm['maxDD_p95']:.1f}%.
* Caveat that robustness checks cannot remove: the whole sample is a gold bull market and the system is long-only. Whether it adds value **beyond being long gold** is only suggestive (p ≈ 0.06 vs random timing). The holdout (2025-07 → 2026-11) contains both a strong rally to new highs and a deep decline (price range visible in the Phase 1 data-audit table: 2026 low ≈ $3,870, high ≈ $5,598), so it tests the system in both conditions.
* **Intraday candidate (NY ORB on high-volatility days) is NOT robust:** only the 30-minute opening range works; 15, 20 and 45 minutes are ≈ 0. With CFI costs only {share.loc[1, 'share VAL > 0'] * 100:.0f}% of variants are positive on validation and {share.loc[1, 'share 2025 > 0'] * 100:.0f}% in 2025; under C2 nearly all lose. A result that exists only at one parameter value is a fitting artefact. **Rejected.**

## 1. Live account specification (CFI, XAUUSD_)

| Item | Value | Used as |
|---|---|---|
| Digits | 3 (1 point = $0.001) | price units |
| Contract size | 100 oz → 0.01 lot = 1 oz | position sizing (Phase 8) |
| Min / step / max lot | 0.01 / 0.01 / 20 | sizing |
| Stop level | 50 points = $0.05 | minimum stop distance |
| Execution / filling | Market execution, IOC | slippage on market orders |
| Swap long / short (points) | −515.76 / +279.2 → −$0.516 / +$0.279 per oz per night (≈ −4.6% / +2.5% per year at $4,071) | swap scenario W_CFI |
| Triple swap | Wednesday | 7 charges per week |
| Spread (screenshot, market closed) | ≈ $0.17 | cost scenario C1_CFI (+$0.07 over the research feed) |
| Commission | not shown in the specification | assumed $0; **please confirm** |

The research data come from another broker. Price behaviour is comparable across brokers; costs are not, so all results below use CFI costs where they matter.

## 2. Swing: every system with the real CFI swap

{md_table(cfi.round(3), "{:.3f}")}

## 3. Swing candidate: parameter neighbourhood (Sharpe, 2-ATR stop, W1 swap)

{md_table(sh.reset_index().astype({"N": str}), "{:.2f}")}

Median Sharpe by stop type (all N × exit combinations): {md_table(stopmed, "{:.2f}")}

Share of the {len(G)} settings with Sharpe > 0: {(G.sharpe > 0).mean() * 100:.0f}%; > 0.5: {(G.sharpe > 0.5).mean() * 100:.0f}%; median {G.sharpe.median():.2f}. No cliff around the chosen setting (N = 20, exit 10, stop 2 ATR).

## 4. Swing candidate: stress tests

{md_table(St.round(3), "{:.3f}")}

Block-bootstrap Monte Carlo of daily P&L (20-day blocks, 5,000 paths, seed 20261107): annual return p5 {sm['ann_ret_p5']:.1f}% / p50 {sm['ann_ret_p50']:.1f}% / p95 {sm['ann_ret_p95']:.1f}%; P(annual return < 0) = {sm['P(ann_ret<0)'] * 100:.1f}%; max drawdown p50 {sm['maxDD_p50']:.1f}% / p95 {sm['maxDD_p95']:.1f}% (1× notional, unlevered).

## 5. Intraday candidate: parameter neighbourhood (avg R, C1_CFI)

{md_table(ic.reset_index().astype({"or_len": str, "vol_quantile": str}), "{:.3f}")}

{md_table(share.round(3), "{:.3f}")}

Monte Carlo on the base setting (C1_CFI, {im['n_trades']} trades): avg R {im['avg_R']:.3f}; shuffled max drawdown p50 {im['shuffle_maxDD_R_p50']:.1f} R / p95 {im['shuffle_maxDD_R_p95']:.1f} R; with 20% of trades randomly missed, avg R p5 = {im['missed20_avgR_p5']:.3f}. The Monte Carlo looks fine, but it cannot rescue a result that depends on one parameter value and fades in 2025.

## 6. Decision

| Candidate | Verdict | Next |
|---|---|---|
| **XAE-Swing v1** (Donchian-20 long-only) | Robust in-sample; edge vs. passive long only suggestive | Rules frozen in `rules/xae_swing_v1.json` → **single holdout run** |
| Intraday ORB high-vol | Not robust (parameter island, decays, fails C2) | **Rejected** |
"""
    (ROOT / "reports" / "06_robustness.md").write_text(rep, encoding="utf-8")
    print("ok")

if __name__ == "__main__":
    main()
