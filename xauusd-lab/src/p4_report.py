"""Builds reports/04_swing_and_regime.md from Phase 4 outputs."""
import json
import pandas as pd
from audit import md_table
from load import ROOT
TAB = ROOT / "reports" / "tables"

def main():
    S = pd.read_csv(TAB / "p4_swing_summary.csv"); Y = pd.read_csv(TAB / "p4_swing_by_year.csv")
    N = json.load(open(ROOT / "reports" / "p4_swing_null.json")); meta = json.load(open(ROOT / "reports" / "p4_swing_meta.json"))
    L = pd.read_csv(TAB / "p3c_experiment_log.csv")
    w1 = S[S.swap == "W1"].drop(columns="swap")
    sw = S.pivot_table(index="system", columns="swap", values="annual_return_%").round(2).reset_index()
    nul = pd.DataFrame(N).T.reset_index().rename(columns={"index": "system"})
    p = L.pivot_table(index="config", columns=["cost", "split"], values="avg_R"); p.columns = [f"avgR_{a}_{b}" for a, b in p.columns]
    n = L[L.cost == "C1"].pivot_table(index="config", columns="split", values=["n", "win_rate", "t_stat", "PF"]); n.columns = [f"{a}_{b}" for a, b in n.columns]
    I = p.join(n).reset_index()
    I = I[["config", "n_dev", "win_rate_dev", "avgR_C0_dev", "avgR_C1_dev", "t_stat_dev", "PF_dev", "avgR_C2_dev", "n_val", "win_rate_val", "avgR_C1_val", "t_stat_val", "avgR_C2_val"]]
    t = pd.read_csv(ROOT / "reports" / "trades" / "V1_orb_vol_regime__regime-high.csv", parse_dates=["t_entry"])
    vy = t.groupby(t.t_entry.dt.year).R.agg(n="size", avg_R="mean", total_R="sum").reset_index().rename(columns={"t_entry": "year"})
    bh = w1[w1.system == "B0_buy_and_hold"].iloc[0]; dc = w1[w1.system == "S1_donchian20_LO"].iloc[0]
    n_total = 88 + 11 + len(S.system.unique()) - 1
    rep = f"""# Phase 4 — Swing trend systems & volatility-regime / hybrid intraday models

_Generated by `src/swing.py`, `src/swing_null.py`, `src/run_phase3.py --c`, `src/p4_report.py`._

## 0. Plain-language summary

* **Swing (multi-day) track:** of 12 classic trend systems, the best was **20-day Donchian breakout, long only**: +{dc['annual_return_%']:.1f}% per year on unlevered notional, max drawdown {dc['maxDD_%']:.1f}%, Sharpe {dc.sharpe:.2f}, no losing year — while invested only {dc['exposure_%']:.0f}% of the time. Buy-and-hold made +{bh['annual_return_%']:.1f}%/yr with a {bh['maxDD_%']:.1f}% drawdown (Sharpe {bh.sharpe:.2f}).
* But it is **only {int(dc.trades)} trades**, and against random long trades of the same number and length its result has p = {N['S1_donchian20_LO']['p_value']:.3f} — suggestive, **not proof**, especially as the best of 12 systems.
* **Every short side lost** (gold rose ~2.5× over the period). Long/short trend systems are not supported by this sample.
* **Intraday track:** the NY opening-range breakout traded **only on high-volatility days** passed the development screen (+{I[I.config.str.contains('high')].avgR_C1_dev.iloc[0]:.3f} R, t = {I[I.config.str.contains('high')].t_stat_dev.iloc[0]:.2f}) but was flat on validation (+{I[I.config.str.contains('high')].avgR_C1_val.iloc[0]:.3f} R) and negative in 2025 → **weak candidate, not accepted.** Compression breakouts and swing-aligned intraday entries showed no edge.
* Configurations tested in total so far: ≈ {n_total}.

## 1. Swing systems — setup

* Daily series 2020-01 → 2025-06 (holdout excluded): D1 segment {meta['segments']['min']['D1']} → {meta['segments']['max']['D1']}, H1-aggregated → {meta['segments']['max']['H1']}, M1-aggregated → {meta['end']}. Evaluation starts {meta['start']} (indicator warm-up); "2020" in the tables is therefore only December.
* Execution at the next day's open with $0.50 per side (wide reopen spread + slippage); stops on daily high/low, gaps fill at the open; financing (swap) scenarios W0 = 0, **W1 = 4%/yr (base)**, W2 = 8%/yr, charged on long and short positions. **The broker's real swap rates are unknown and matter a lot for swing trading.**
* Systems (classic defaults, not optimised): Donchian 20/55 (exit on the opposite N/2 channel, 2-ATR initial stop with ATR trail), EMA 20/50 and 50/200 crossover (3-ATR chandelier stop; after a stop, flat until the next cross), time-series momentum 20/60 days (weekly rebalance, no stop). LS = long & short, LO = long only.

## 2. Swing results (W1 swap)

{md_table(w1.round(3), "{:.3f}")}

Return by calendar year, % of notional (W1):

{md_table(Y.round(1).fillna(0).astype({"system": str}), "{:.1f}")}

Annual return under the three swap scenarios (%/yr):

{md_table(sw, "{:.2f}")}

## 3. Is the timing real? Random-timing null (long-only systems)

Each system's trade lengths are kept and placed at random non-overlapping dates (5,000 draws, seed 20261107, same costs and swap, no stop):

{md_table(nul, "{:.3f}")}

Only Donchian-20 LO comes close to significance (p ≈ {N['S1_donchian20_LO']['p_value']:.2f}); with 12 systems tried, a p of 0.06 for the best one is expected roughly half the time by chance alone. **Status: promising candidate, needs robustness checks and the untouched holdout.**

## 4. Intraday: volatility regime and hybrid models (C1 unless stated)

{md_table(I.round(3), "{:.3f}")}

V1 (ORB on high-volatility days) by year (C1):

{md_table(vy.round(3).astype({"year": str}), "{:.3f}")}

* V1-high is the first intraday variant to pass the DEV screen, and it fits the Phase 2 finding (costs are a smaller share of the move on high-volatility days). But the result decays: strong 2024, negative 2025, flat on VAL, negative under C2. With ≈ 100 configurations tried, t ≈ 2.2 is about what the best of many random tries would show. **Status: REVISE — watch-list only.**
* Compression breakouts (V2): negative even before slippage. Swing-aligned intraday entries (V3): ≈ 0. The daily trend direction does not make intraday breakouts or pullbacks profitable.

## 5. Where this leaves the research

| Candidate | Evidence | Status |
|---|---|---|
| Swing: Donchian-20, long only | best of 12; Sharpe {dc.sharpe:.2f}; p ≈ {N['S1_donchian20_LO']['p_value']:.2f} vs random timing; {int(dc.trades)} trades | **Candidate** → robustness + holdout |
| Intraday: NY ORB-30 on high-volatility days | DEV t ≈ 2.2; VAL ≈ 0; 2025 negative | **Watch-list** → robustness + holdout |
| All other intraday ideas (≈ 95 variants) | no edge after costs | Rejected |

Next (Phase 6 of the plan): parameter-sensitivity and Monte-Carlo tests on the two candidates, then **one single run on the untouched holdout (2025-07 → 2026-11)**, with rules frozen beforehand.
"""
    (ROOT / "reports" / "04_swing_and_regime.md").write_text(rep, encoding="utf-8")
    print("ok")

if __name__ == "__main__":
    main()
