"""Builds reports/03b_walkforward.md from p3b log and walk-forward tables."""
import pandas as pd
from audit import md_table
from load import ROOT
TAB = ROOT / "reports" / "tables"

def main():
    L = pd.read_csv(TAB / "p3b_experiment_log.csv")
    p = L.pivot_table(index="config", columns=["cost", "split"], values="avg_R")
    p.columns = [f"avgR_{a}_{b}" for a, b in p.columns]
    n = L[L.cost == "C1"].pivot_table(index="config", columns="split", values=["n", "t_stat"])
    n.columns = [f"{a}_{b}" for a, b in n.columns]
    M = p.join(n).reset_index()
    M = M[["config", "n_dev", "avgR_C0_dev", "avgR_C1_dev", "t_stat_dev", "avgR_C2_dev", "n_val", "avgR_C0_val", "avgR_C1_val", "t_stat_val", "avgR_C2_val"]]
    passed = int(((M.n_dev >= 100) & (M.avgR_C1_dev > 0) & (M.t_stat_dev >= 2)).sum())
    S = pd.read_csv(TAB / "wf_summary.csv"); F = pd.read_csv(TAB / "wf_folds.csv")
    l0 = pd.read_csv(TAB / "p3_experiment_log.csv")
    total = l0.config.nunique() - 3 + L.config.nunique()
    best = S.iloc[0]
    lab = S[S.track.str.startswith("LAB")].iloc[0]
    rep = f"""# Phase 3b — Inverted hypotheses, wider exits, trend filter, and walk-forward validation

_Generated by `src/run_phase3.py --b`, `src/walkforward.py`, `src/p3b_report.py`._

## 0. Plain-language summary

* The ideas that lost in Phase 3 were inverted exactly (same signals, opposite direction) — **the inverses also lose.** When an idea and its mirror both lose, the idea carries **no directional information**; the losses were simply trading costs.
* Wider stops/targets and a daily-trend filter did not create an edge either: {passed} of {len(M)} new variants pass the development screen.
* **Walk-forward** (choose on the past 12 months, trade the next 3 months, repeat 9 times, 2023-04 → 2025-06): the best family track made {best.avg_R:+.3f} R per trade (t = {best.t_stat:.2f}, {int(best.n)} trades) — not statistically different from zero. The "lab" process of picking last year's best variant from everything lost {lab.avg_R:+.3f} R per trade: **last year's winners did not keep winning.**
* Total configurations tested so far: **{total}**. Verdict for intraday rule-based setups built from these schools: **no proven edge after costs.**

## 1. New variants (Phase 3b), C0/C1/C2 avg R

{md_table(M.round(3), "{:.3f}")}

Reading: H06 (fade Bollinger) and its exact mirror H10 (follow Bollinger) are *both* negative at C0 in DEV (≈ −0.05 R each), i.e. gross ≈ 0 and the sum equals the spread paid twice. H02 (fade Asian sweep) and its mirror H09 behave the same way. H11 "Asian acceptance" momentum is strongly negative in 2022–24 and positive in 2024–25 — a regime flip, not an edge.

## 2. Walk-forward, out-of-sample (C1)

Train 12 months → test next 3 months; 9 folds from 2023-04 to 2025-06. Within each family the configuration with the best positive train avg R (≥ 40 trades) is traded in the next quarter; otherwise the track stays flat.

{md_table(S.round(3).astype(dict(avg_R_by_year=str)), "{:.3f}")}

Fold-by-fold choices: `reports/tables/wf_folds.csv`; every out-of-sample trade: `reports/tables/wf_oos_trades.csv`.

* No track reaches t ≥ 2. The two best (H05 trend pullback, H11 wide breakout) earn almost all of their result in 2025, the strongest gold up-trend in the sample.
* H04 NY opening-range breakout — the best Phase 3 candidate — is ≈ 0 out of sample ({S[S.track.str.startswith('H04')].avg_R.iloc[0]:+.3f} R).

## 3. Conclusions

1. On this data, **intraday direction is not predictable enough to pay ≈ 0.10 R of costs per trade** with the classic Price-Action / ICT / breakout / mean-reversion setups, as defined here.
2. The only consistently positive periods coincide with strong multi-week trends (2024-H2 → 2025). That points to **trend persistence on multi-day horizons**, where costs are a far smaller share of the move — but that is a swing-trading question, outside the original scalping/intraday brief.
3. Remaining intraday avenues the data still allows: (a) volatility-regime conditioning (the one robust property found in Phase 2), (b) scheduled-news behaviour, which needs a dated economic calendar.

The decision on which direction to pursue next is the user's: see the chat summary.
"""
    (ROOT / "reports" / "03b_walkforward.md").write_text(rep, encoding="utf-8")
    print("ok")

if __name__ == "__main__":
    main()
